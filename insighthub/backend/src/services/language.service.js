export function translateText(text, targetLang, category = 'general', options = {}) {
  if (!text) return '';
  if (!targetLang || targetLang === 'English') {
    return text;
  }

  const langConfig = translations[targetLang];
  if (!langConfig) {
    return `[${targetLang}] ${text}`;
  }

  if (options.variant === 'title') {
    const clipped = text.length > 100 ? `${text.slice(0, 100)}…` : text;
    return `${langConfig.prefix}${clipped}`;
  }

  const categorySnippet = langConfig.categoryMap[category] || langConfig.categoryMap.general;
  const clipped = text.length > 120 ? `${text.slice(0, 120)}...` : text;
  return `${langConfig.prefix}${categorySnippet}"${clipped}"${langConfig.suffix}`;
}

function translateDigest2Min(digest, targetLang) {
  const copy = DIGEST_COPY[targetLang];
  if (!copy) return digest;

  const lines = digest.split('\n');
  const items = [];

  for (const line of lines) {
    const match = line.match(/^(\d+)\.\s+\*\*(.+?)\*\*\s*-\s*(.+)$/);
    if (!match) continue;

    const [, num, title, description] = match;
    const translatedTitle = translateText(title, targetLang, 'general', { variant: 'title' });
    const translatedDescription = translateText(description, targetLang, 'general');
    items.push(`${num}. **${translatedTitle}** - ${translatedDescription}`);
  }

  if (items.length === 0) return digest;

  return `${copy.intro2Min}\n\n${items.join('\n')}\n\n${copy.tip2Min}`;
}

function translateDigest5Min(digest, targetLang) {
  const copy = DIGEST_COPY[targetLang];
  if (!copy) return digest;

  const sections = digest.split(/\n(?=### \[Update)/);
  const translatedSections = [];

  for (const section of sections) {
    const trimmed = section.trim();
    if (!trimmed) continue;

    if (trimmed.startsWith('Your comprehensive')) continue;
    if (trimmed.startsWith('This concludes')) continue;

    const headerMatch = trimmed.match(/^### \[Update (\d+)\] (.+?)(?:\n|$)/);
    if (!headerMatch) continue;

    const [, updateNum, title] = headerMatch;
    const rest = trimmed.slice(headerMatch[0].length);
    const contextMatch = rest.match(/\*\*Context:\*\*\s*(.+?)(?:\n\*\*Insight:|\n>|$)/s);
    const schemeMatch = rest.match(/>\s*\*\*Government Scheme Identified:\*\*\s*(.+?)(?:\n\*\*Insight:|$)/s);
    const insightMatch = rest.match(/\*\*Insight:\*\*\s*(.+?)$/s);

    const contextText = contextMatch?.[1]?.trim() || '';
    const schemeText = schemeMatch?.[1]?.trim() || '';
    const insightText = insightMatch?.[1]?.trim() || '';

    let block = `### [Update ${updateNum}] ${translateText(title, targetLang, 'general', { variant: 'title' })}\n`;
    if (contextText) {
      block += `${copy.contextLabel} ${translateText(contextText, targetLang, 'general')}\n`;
    }
    if (schemeText) {
      block += `> ${copy.schemeLabel} ${translateText(schemeText, targetLang, 'general')}\n`;
    }
    if (insightText) {
      block += `${copy.insightLabel} ${translateText(insightText, targetLang, 'general')}\n`;
    }

    translatedSections.push(block.trimEnd());
  }

  if (translatedSections.length === 0) return digest;

  return `${copy.intro5Min}\n\n${translatedSections.join('\n\n')}\n\n${copy.outro5Min}`;
}

export function translateDigest(digest, targetLang) {
  if (!digest || !targetLang || targetLang === 'English') {
    return digest;
  }

  if (digest.includes('2-minute morning brief')) {
    return translateDigest2Min(digest, targetLang);
  }

  if (digest.includes('5-minute news intelligence brief')) {
    return translateDigest5Min(digest, targetLang);
  }

  return digest;
}

export function translateArticleFields(article, targetLang) {
  const category = article.category || 'general';
  const title = article.title || '';
  const summary = article.description || article.title || '';

  if (!targetLang || targetLang === 'English') {
    return { title, summary };
  }

  return {
    title: translateText(title, targetLang, category, { variant: 'title' }),
    summary: translateText(summary, targetLang, category),
  };
}

export default { translateText, translateDigest, translateArticleFields };
